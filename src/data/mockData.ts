export function calculateSavingsPercent(item: CatalogItem): number {
  if (item.retailPrice <= 0) return 0;
  const pct = Math.round(((item.retailPrice - item.rate) / item.retailPrice) * 100);
  return Math.max(10, Math.min(96, pct));
}

